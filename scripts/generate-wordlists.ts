import { promises as fs } from "fs";
import path from "path";

const DATA_DIR = path.resolve(process.cwd(), "data");
const ANSWERS_DIR = path.join(DATA_DIR, "answers");
const OUTPUT_DIR = path.resolve(process.cwd(), "constants", "wordlists");
const METADATA_FILE = path.resolve(process.cwd(), "constants", "wordlist-metadata.ts");
const MANIFEST_FILE = path.resolve(process.cwd(), "constants", "wordlist-manifest.ts");
const LEGACY_FILE = path.resolve(process.cwd(), "constants", "wordlist.ts");

const WORD_LENGTHS = [3, 4, 5, 6, 7, 8, 9, 10, 11] as const;
const VALID_WORD_REGEX = new RegExp(String.raw`^[A-Za-zÄÖÜäöüßẞ]+$`, "u");
const DIACRITIC_MARKS = new RegExp(String.raw`\p{Diacritic}`, "gu");
const SCRIPT_HEADER = `// This file is auto-generated by scripts/generate-wordlists.ts
// Do not edit manually. Update data/<length>.txt or data/answers/<length>.txt and rerun the script.
`;

const warningMessages: string[] = [];
const collator = new Intl.Collator("de", { sensitivity: "base", usage: "sort" });

const keepDiacriticsFor = new Map<string, string>();

const wordLengthToFiles = WORD_LENGTHS.map((length) => {
  const lengthKey = length.toString().padStart(2, "0");
  return {
    length,
    allowFile: path.join(DATA_DIR, `${lengthKey}.txt`),
    answersFile: path.join(ANSWERS_DIR, `${lengthKey}.txt`),
  };
});

function stripAccents(word: string): string {
  let protectedWord = word;
  keepDiacriticsFor.forEach((placeholder, char) => {
    protectedWord = protectedWord.replace(new RegExp(char, "g"), placeholder);
  });

  const normalized = protectedWord
    .normalize("NFD")
    .replace(DIACRITIC_MARKS, "")
    .normalize("NFC");

  let restored = normalized;
  keepDiacriticsFor.forEach((placeholder, char) => {
    restored = restored.replace(new RegExp(placeholder, "g"), char);
  });

  return restored;
}

function sortWords(words: Iterable<string>): string[] {
  return Array.from(new Set(words)).sort((a, b) => collator.compare(a, b));
}

function getGraphemeLength(word: string): number {
  return Array.from(word).length;
}

function validateWord(word: string, source: string, expectedLength: number): void {
  const length = getGraphemeLength(word);
  if (length !== expectedLength) {
    throw new Error(
      `Ungültiges Wort '${word}' (Quelle: ${source}). Erwartet: ${expectedLength} Zeichen.`
    );
  }

  if (!VALID_WORD_REGEX.test(word)) {
    throw new Error(
      `Ungültiges Wort '${word}' (Quelle: ${source}). Nur deutsche Buchstaben erlaubt.`
    );
  }
}

async function readWordList(
  filePath: string,
  description: string,
  expectedLength: number
): Promise<string[]> {
  try {
    const raw = await fs.readFile(filePath, "utf8");
    return raw
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter(Boolean)
      .map((word) => {
        const lower = word.toLocaleLowerCase("de-DE");
        validateWord(lower, description, expectedLength);
        return lower;
      });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      throw new Error(`Die erforderliche Datei wurde nicht gefunden: ${filePath}`);
    }
    throw error;
  }
}

function buildAccentMap(words: string[]): Record<string, string> {
  const map = new Map<string, string>();
  const wordSet = new Set(words);

  for (const word of words) {
    const base = stripAccents(word);

    if (base === word) {
      continue;
    }

    if (wordSet.has(base)) {
      continue;
    }

    const existing = map.get(base);
    if (existing && existing !== word) {
      warningMessages.push(
        `Warnung: mehrere Wörter mit gleicher Grundform -> '${base}' (${existing} vs ${word}).`
      );
      continue;
    }

    map.set(base, word);
  }

  return Object.fromEntries(
    Array.from(map.entries()).sort((a, b) => collator.compare(a[0], b[0]))
  );
}

function formatStringArray(values: string[]): string {
  if (values.length === 0) {
    return "[] as const";
  }

  return JSON.stringify(values, null, 2) + " as const";
}

function formatRecord(record: Record<string, string>): string {
  const entries = Object.entries(record);
  if (entries.length === 0) {
    return "{} as const";
  }

  return JSON.stringify(record, null, 2) + " as const";
}

function indentMultiline(value: string, spaces: number): string {
  const indent = " ".repeat(spaces);
  return value
    .split("\n")
    .map((line, index) => (index === 0 ? line : indent + line))
    .join("\n");
}

async function ensureDirectories(): Promise<void> {
  await fs.mkdir(DATA_DIR, { recursive: true });
  await fs.mkdir(ANSWERS_DIR, { recursive: true });
  await fs.rm(OUTPUT_DIR, { recursive: true, force: true });
  await fs.mkdir(OUTPUT_DIR, { recursive: true });
}

async function generateWordLists(): Promise<void> {
  await ensureDirectories();

  const wordLists: Array<{
    length: number;
    answers: string[];
    allowed: string[];
    accentMap: Record<string, string>;
  }> = [];

  for (const { length, allowFile, answersFile } of wordLengthToFiles) {
    const answers = sortWords(
      await readWordList(answersFile, `answers/${path.basename(answersFile)}`, length)
    );
    const allowedSource = await readWordList(allowFile, path.basename(allowFile), length);

    const allowed = sortWords([...allowedSource, ...answers]);
    const accentMap = buildAccentMap(allowed);

    const allowedSet = new Set(allowed);
    const missingAnswers = answers.filter((word) => !allowedSet.has(word));
    if (missingAnswers.length > 0) {
      warningMessages.push(
        `Warnung: Antwortwörter fehlen in der Gesamtliste (${length} Buchstaben): ${missingAnswers.join(", ")}`
      );
    }

    wordLists.push({ length, answers, allowed, accentMap });
  }

  const metadataContent = `${SCRIPT_HEADER}
export const WORD_LENGTHS = [${WORD_LENGTHS.join(", ")}] as const;
export type WordLength = typeof WORD_LENGTHS[number];
export type AccentMap = Record<string, string>;
export interface WordListData {
  readonly allowed: readonly string[];
  readonly answers: readonly string[];
  readonly accentMap: AccentMap;
}

export interface WordListStats {
  readonly answers: number;
  readonly allowed: number;
  readonly unique: number;
}

export interface AllowedWordListPayload {
  readonly allowed: readonly string[];
  readonly accentMap: AccentMap;
  readonly stats: WordListStats;
}

export interface AnswerWordListPayload {
  readonly answers: readonly string[];
}
`;

  await fs.writeFile(METADATA_FILE, metadataContent, "utf8");

  const manifestEntries = wordLists
    .map(({ length, allowed, answers, accentMap }) => {
      const uniqueCount = new Set([
        ...allowed,
        ...answers,
        ...Object.keys(accentMap),
        ...Object.values(accentMap),
      ]).size;
      const stats = {
        allowed: allowed.length,
        answers: answers.length,
        accentEntries: Object.keys(accentMap).length,
        unique: uniqueCount,
      };
      return `  ${length}: ${JSON.stringify(stats)} as const`;
    })
    .join(",\n");

  const manifestContent = `${SCRIPT_HEADER}
import type { WordLength } from "./wordlist-metadata";

export interface WordListSummary {
  readonly allowed: number;
  readonly answers: number;
  readonly accentEntries: number;
  readonly unique: number;
}

export const WORD_LIST_SUMMARY: Record<WordLength, WordListSummary> = {
${manifestEntries}
} as const;
`;

  await fs.writeFile(MANIFEST_FILE, manifestContent, "utf8");

  for (const { length, allowed, answers, accentMap } of wordLists) {
    const allowedBlock = indentMultiline(formatStringArray(allowed), 2);
    const answersBlock = indentMultiline(formatStringArray(answers), 2);
    const accentMapBlock = indentMultiline(formatRecord(accentMap), 2);

    const moduleContent = `${SCRIPT_HEADER}
import type { WordListData } from "../wordlist-metadata";

const wordList: WordListData = {
  allowed: ${allowedBlock},
  answers: ${answersBlock},
  accentMap: ${accentMapBlock},
};

export default wordList;
`;

    const modulePath = path.join(OUTPUT_DIR, `length-${length}.ts`);
    await fs.writeFile(modulePath, moduleContent, "utf8");
  }

  await fs.rm(LEGACY_FILE, { force: true });

  console.log(`Wortlisten erstellt in ${OUTPUT_DIR}`);
  wordLists.forEach(({ length, allowed, answers, accentMap }) => {
    console.log(
      `Länge ${length}: erlaubte=${allowed.length}, antworten=${answers.length}, umlaute=${Object.keys(accentMap).length}`
    );
  });

  if (warningMessages.length > 0) {
    console.warn("\n--- Warnungen ---");
    warningMessages.forEach((message) => console.warn(message));
  }
}

generateWordLists().catch((error) => {
  console.error("Fehler beim Erzeugen der Wortlisten:\n", error);
  process.exitCode = 1;
});
